"""Generate the ``sample/xmake.lua`` annotation fixture from ``library/``."""

from __future__ import annotations

import json
import re
from pathlib import Path

FUNCTION_RE = re.compile(r"^function (.*?)\((.*?)\) end$")
PARAM_RE = re.compile(r"^---@param (\S+?) (\S+)")

# Files that are exercised as top-level xmake definitions instead of through the
# helper function that holds script modules and instance methods.
TOP_LEVEL_FILES = {
    "global_interfaces",
    "conditions",
    "project_target",
    "configuration_option",
    "custom_rule",
    "custom_toolchain",
    "package_dependencies",
    "plugin_and_task",
    "xpack_interfaces",
    "xpack_component_interfaces",
}

SCOPE_ENDS = {
    "project_target": "target_end",
    "configuration_option": "option_end",
    "custom_rule": "rule_end",
    "custom_toolchain": "toolchain_end",
    "plugin_and_task": "task_end",
}

INSTANCE_TYPES = {
    "Bytes": "sample_bytes",
    "Event": "sample_event",
    "Package": "sample_package",
    "View": "sample_view",
}


class SampleGenerator:
    """Render a Lua file that calls every function declared in ``library/``."""

    def __init__(
        self,
        library_dir: str | Path,
        output_file: str | Path,
        schema_file: str | Path,
    ):
        self.library_dir = Path(library_dir)
        self.output_file = Path(output_file)
        self.schema_file = Path(schema_file)
        self._classes: set[str] | None = None

    def generate(self) -> str:
        """Write the sample file and return its path."""
        self.output_file.parent.mkdir(parents=True, exist_ok=True)
        self.output_file.write_text(self.render(), encoding="utf-8")
        return str(self.output_file)

    def render(self) -> str:
        """Render the sample source without writing it."""
        documents = self._parse_library()
        by_base = {document["base"]: document for document in documents}

        lines: list[str] = [
            "-- Auto-generated annotation fixture: every API in ../library is called once.",
            "-- It exists to exercise the generated annotations with a language server, not",
            "-- to be a runnable xmake project. Do not edit this file by hand.",
            "",
            "---@diagnostic disable: unused-local, unused-function, discard-returns",
            "",
        ]

        def emit_file(base: str, indent: str = "") -> None:
            document = by_base[base]
            lines.append(f"{indent}-- library/{base}.lua")
            for function in document["functions"]:
                lines.append(f"{indent}{self._render_call(base, function)}")
            lines.append("")

        def emit_scoped_file(base: str, indent: str = "") -> None:
            document = by_base[base]
            functions = document["functions"]
            end_signature = SCOPE_ENDS.get(base)
            lines.append(f"{indent}-- library/{base}.lua")
            if functions:
                lines.append(f"{indent}{self._render_call(base, functions[0])}")
            for function in functions[1:]:
                if function["signature"] == end_signature:
                    continue
                lines.append(f"{indent}{self._render_call(base, function)}")
            if end_signature:
                end_function = next(
                    (
                        function
                        for function in functions
                        if function["signature"] == end_signature
                    ),
                    None,
                )
                if end_function is not None:
                    lines.append(f"{indent}{self._render_call(base, end_function)}")
            lines.append("")

        # Global configuration and xmake scope definitions.
        lines.extend(["--- Global interfaces and conditions", ""])
        if "global_interfaces" in by_base:
            emit_file("global_interfaces")
        if "conditions" in by_base:
            emit_file("conditions")

        if "project_target" in by_base:
            lines.extend(["--- Target scope", ""])
            emit_scoped_file("project_target", "    ")

        if "configuration_option" in by_base:
            lines.extend(["--- Option scope", ""])
            emit_scoped_file("configuration_option", "    ")

        if "custom_rule" in by_base:
            lines.extend(["--- Rule scope", ""])
            emit_scoped_file("custom_rule", "    ")

        if "custom_toolchain" in by_base:
            lines.extend(["--- Toolchain scope", ""])
            emit_scoped_file("custom_toolchain", "    ")

        if "package_dependencies" in by_base:
            lines.extend(["--- Package scope", ""])
            emit_file("package_dependencies", "    ")

        if "plugin_and_task" in by_base:
            lines.extend(["--- Task/plugin scope", ""])
            emit_scoped_file("plugin_and_task", "    ")

        if "xpack_interfaces" in by_base or "xpack_component_interfaces" in by_base:
            lines.extend(["--- XPack scope", 'includes("@builtin/xpack")', ""])
            if "xpack_interfaces" in by_base:
                lines.extend(
                    [
                        "---@diagnostic disable-next-line: undefined-global",
                        'xpack("sample_xpack")',
                    ]
                )
                for function in by_base["xpack_interfaces"]["functions"]:
                    lines.append(f"    {self._render_call('xpack_interfaces', function)}")
                lines.append("")
            if "xpack_component_interfaces" in by_base:
                lines.extend(
                    [
                        "---@diagnostic disable-next-line: undefined-global",
                        'xpack_component("sample_component")',
                    ]
                )
                for function in by_base["xpack_component_interfaces"]["functions"]:
                    lines.append(
                        f"        {self._render_call('xpack_component_interfaces', function)}"
                    )
                lines.append("")
            lines.append("")

        # Script modules and instance classes cannot be executed while xmake
        # parses the project, so they live in an uncalled helper function.
        lines.extend(
            [
                "--- Script modules and instance APIs",
                "local function exercise_script_modules()",
                "    ---@type thread",
                "    local sample_coroutine_thread",
                "    ---@type Bytes",
                "    local sample_bytes = {}",
                "    ---@type Event",
                "    local sample_event = {}",
                "    ---@type Package",
                "    local sample_package = {}",
                "    ---@type View",
                "    local sample_view = {}",
                "",
            ]
        )

        instance_vars: dict[str, str] = {}
        for document in documents:
            class_name = document["class_name"]
            has_methods = any(
                ":" in function["signature"] for function in document["functions"]
            )
            if not class_name or not has_methods:
                continue

            instance_var = INSTANCE_TYPES.get(
                class_name, f"sample_{class_name.casefold()}"
            )
            instance_vars[class_name] = instance_var
            if class_name not in INSTANCE_TYPES:
                lines.append(f"    ---@type {class_name}")
                lines.append(f"    local {instance_var} = {{}}")

        lines.append("")

        for document in documents:
            base = document["base"]
            if base in TOP_LEVEL_FILES:
                continue

            class_name = document["class_name"]
            instance_var = instance_vars.get(class_name) if class_name else None
            lines.append(f"    -- library/{base}.lua")
            for function in document["functions"]:
                if instance_var and ":" in function["signature"]:
                    lines.append(
                        f"    {self._render_call(base, function, instance=instance_var)}"
                    )
                else:
                    lines.append(f"    {self._render_call(base, function)}")
            lines.append("")

        lines.extend(["end", ""])
        return "\n".join(lines)

    def _parse_library(self) -> list[dict]:
        documents = []
        for path in sorted(self.library_dir.glob("*.lua")):
            text = path.read_text(encoding="utf-8")
            class_match = re.search(r"^---@class (\S+)$", text, re.MULTILINE)
            class_name = class_match.group(1) if class_match else None

            functions = []
            params: dict[str, str] = {}
            for line in text.splitlines():
                param_match = PARAM_RE.match(line)
                if param_match:
                    name = param_match.group(1).rstrip("?")
                    params[name] = param_match.group(2)
                    continue

                function_match = FUNCTION_RE.match(line)
                if not function_match:
                    continue

                arguments = [
                    arg.strip()
                    for arg in function_match.group(2).split(",")
                    if arg.strip()
                ]
                functions.append(
                    {
                        "signature": function_match.group(1),
                        "arguments": arguments,
                        "params": dict(params),
                    }
                )
                params = {}

            documents.append(
                {
                    "base": path.stem,
                    "class_name": class_name,
                    "functions": functions,
                }
            )
        return documents

    def _render_call(
        self,
        file_base: str,
        function: dict,
        *,
        instance: str | None = None,
    ) -> str:
        signature = function["signature"]
        if signature == "includes":
            args = '"@builtin/xpack"'
        else:
            args = ", ".join(self._render_arguments(function))

        if instance is not None and ":" in signature:
            method = signature.split(":", 1)[1]
            call = f"{instance}:{method}({args})"
        else:
            call = f"{signature}({args})"
        return f"{call} -- @api {file_base}.{signature}"

    def _render_arguments(self, function: dict) -> list[str]:
        rendered = []
        params = function["params"]
        for argument in function["arguments"]:
            if argument == "...":
                rendered.append('"sample"')
                continue
            name = argument.rstrip("?").strip()
            rendered.append(self._placeholder(params.get(name, "any")))
        return rendered

    def _placeholder(self, type_name: str) -> str:
        type_name = type_name.strip().rstrip("?")
        first = type_name.split("|")[0].strip()

        if first.startswith("fun") or first == "function":
            return "function() end"
        if first == "thread":
            return "sample_coroutine_thread"
        if first in INSTANCE_TYPES:
            return INSTANCE_TYPES[first]
        if first in self._schema_classes() or first == "Rect":
            return "{}"
        if first in ("number", "integer"):
            return "1"
        if first == "boolean":
            return "true"
        if first in ("table", "array", "file"):
            return "{}"
        if first == "any":
            return "nil"
        # String and every string-based enum alias accept an arbitrary string.
        return '"sample"'

    def _schema_classes(self) -> set[str]:
        if self._classes is None:
            if not self.schema_file.is_file():
                self._classes = set()
            else:
                data = json.loads(self.schema_file.read_text(encoding="utf-8"))
                self._classes = set(data.get("classes", {}))
        return self._classes
